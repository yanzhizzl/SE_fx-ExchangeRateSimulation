_QUESTION_CACHE: dict = {}


def _all_questions() -> dict:
    if _QUESTION_CACHE:
        return _QUESTION_CACHE
    for (subject, level), pool in RAW_QUESTIONS.items():
        for index, item in enumerate(pool):
            item = dict(item)
            item.setdefault("type", "choice")
            # 基础题三个年级共用，保证每个「年级 × 学科 × 难度」都有多道候选题；
            # 年级专属题仍通过显式 grades 字段限制。
            grades = item.get("grades") or list(GRADE_IDS)
            item["grades"] = [grade for grade in grades if grade in GRADE_META]
            item["id"] = f"{subject}-{level}-{index}"
            item["subject"] = subject
            item["difficulty"] = level
            _QUESTION_CACHE.setdefault((subject, level), []).append(item)
    return _QUESTION_CACHE


def nearest_level(subject: str, level: int) -> int:
    """题库缺少指定难度时，选择最接近的可用难度。"""
    levels = [lvl for (sub, lvl) in RAW_QUESTIONS if sub == subject]
    if not levels:
        levels = [lvl for (_, lvl) in RAW_QUESTIONS]
    return min(levels, key=lambda lvl: (abs(lvl - level), lvl))


def _grade_pool(subject: str, level: int, grade: str) -> list:
    bank = _all_questions()
    exact = [
        item for item in bank.get((subject, int(level)), []) if grade in item["grades"]
    ]
    if exact:
        return exact
    # 保证题目一定来自当前年级题库；该年级没有精确难度时，退到同年级的最近难度。
    levels = sorted(
        {
            lvl
            for (sub, lvl), pool in bank.items()
            if sub == subject and any(grade in item["grades"] for item in pool)
        },
        key=lambda lvl: (abs(lvl - int(level)), lvl),
    )
    for lvl in levels:
        pool = [
            item
            for item in bank.get((subject, lvl), [])
            if grade in item["grades"]
        ]
        if pool:
            return pool
    return []


def _normalize_text(value: object) -> str:
    text = unicodedata.normalize("NFKC", str(value or "")).strip().lower()
    text = re.sub(r"[\s，。；、,.!！?？:：'\"“”‘’（）()《》]", "", text)
    return text


def check_answer(question: dict, selected: Optional[int] = None, text: str = "") -> bool:
    """统一判题：支持单选、判断、填空和数值题。"""
    kind = question.get("type", "choice")
    if kind in ("choice", "judge"):
        return selected is not None and selected == question.get("answer")
    answers = question.get("answers", [])
    if kind == "fill":
        user = _normalize_text(text)
        return bool(user) and any(user == _normalize_text(answer) for answer in answers)
    if kind == "numeric":
        try:
            raw = unicodedata.normalize("NFKC", str(text or "")).replace(",", "").strip()
            user_value = float(raw)
        except (TypeError, ValueError):
            return False
        tolerance = float(question.get("tolerance", 0.01))
        for answer in answers:
            try:
                target = float(answer)
            except (TypeError, ValueError):
                continue
            if math.isclose(user_value, target, abs_tol=max(1e-9, tolerance)):
                return True
        return False
    return False


def get_question(
    subject: str,
    difficulty: int,
    recent_ids: Iterable[str] = (),
    rng: Optional[random.Random] = None,
    grade: Optional[str] = None,
) -> dict:
    """返回一道题；传入 grade 时严格从该年级题库中抽取。"""
    rng = rng or random
    bank = _all_questions()
    level = int(max(1, min(4, difficulty)))
    if grade in GRADE_META:
        pool = _grade_pool(subject, level, grade)
    else:
        pool = bank.get((subject, level), [])
        if not pool:
            pool = bank.get((subject, nearest_level(subject, level)), [])
    if not pool:
        subject = "数学"
        pool = _grade_pool(subject, 1, grade) if grade in GRADE_META else bank.get((subject, 1), [])

    recent_list = list(recent_ids)
    recent = set(recent_list)
    fresh = [q for q in pool if q["id"] not in recent]
    candidates = fresh or pool
    # 全部轮过一遍后，也尽量避免连续出现与上一题完全相同的题目。
    if len(candidates) > 1 and recent_list:
        last_id = recent_list[-1]
        without_last = [q for q in candidates if q["id"] != last_id]
        if without_last:
            candidates = without_last
    source = rng.choice(candidates)
    kind = source.get("type", "choice")
    assigned_grade = grade if grade in GRADE_META else (source.get("grades") or ["g1"])[0]
    result = {
        "id": source["id"],
        "subject": subject,
        "difficulty": source["difficulty"],
        "type": kind,
        "type_label": QUESTION_TYPE_META.get(kind, QUESTION_TYPE_META["choice"])["label"],
        "prompt": source["q"],
        "explain": source["explain"],
        "options": [],
        "answer": None,
        "answers": list(source.get("answers", [])),
        "input_hint": source.get("input_hint", ""),
        "tolerance": source.get("tolerance", 0.01),
        "grades": list(source.get("grades", [])),
        "grade": assigned_grade,
        "grade_label": GRADE_META.get(assigned_grade, {}).get("name", ""),
    }
    if kind in ("choice", "judge"):
        options = list(source.get("options", []))
        if len(options) < 2 or source.get("answer") is None:
            options = ["正确", "错误"]
            source = dict(source)
            source["answer"] = 0
        correct_text = options[source["answer"]]
        rng.shuffle(options)
        result["options"] = options
        result["answer"] = options.index(correct_text)
        result["correct_display"] = correct_text
    else:
        answers = result["answers"]
        result["correct_display"] = answers[0] if answers else "见解析"
    return result


def grade_pool_size(grade: str) -> int:
    return sum(
        1
        for pool in _all_questions().values()
        for question in pool
        if grade in question["grades"]
    )


def grade_counts() -> dict:
    return {grade: grade_pool_size(grade) for grade in GRADE_IDS}


def pool_size() -> int:
    return sum(len(pool) for pool in RAW_QUESTIONS.values())
