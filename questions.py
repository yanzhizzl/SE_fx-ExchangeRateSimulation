def difficulty_for_leverage(leverage: int) -> int:
    """把 1–75 倍杠杆映射到四档题目难度。"""
    try:
        lev = int(max(1, min(75, int(leverage))))
    except (TypeError, ValueError):
        lev = 1
    if lev <= 1:
        return 1
    if lev <= 3:
        return 2
    if lev <= 9:
        return 3
    return 4


